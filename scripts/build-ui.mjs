#!/usr/bin/env node
// Bundle the MCP App client (src/ui/main.ts -> client.ts) and stylesheet into
// src/ui/app.generated.ts, which the server inlines into the app HTML. The
// output is checked in, like the corpus, so the Worker and stdio builds need
// no extra loader. `--check` fails when the checked-in file is stale.

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const args = process.argv.slice(2);
const check = args.includes("--check");
const outArg = args.find((arg) => arg.startsWith("--out="))?.slice(6);
const outputPath = resolve(outArg ?? `${root}src/ui/app.generated.ts`);

export async function renderModule() {
	const bundle = await build({
		entryPoints: [`${root}src/ui/main.ts`],
		bundle: true,
		write: false,
		format: "iife",
		platform: "browser",
		target: "es2020",
		charset: "utf8",
		legalComments: "none",
		logLevel: "silent",
	});
	const script = bundle.outputFiles[0]?.text;
	if (!script) throw new Error("esbuild produced no output for main.ts");
	const css = await readFile(`${root}src/ui/styles.css`, "utf8");
	return [
		"// AUTO-GENERATED by scripts/build-ui.mjs from src/ui/client.ts and",
		"// src/ui/styles.css — do not edit by hand. Run `npm run build:ui`.",
		"",
		`export const APP_CSS = ${JSON.stringify(css)};`,
		"",
		`export const APP_SCRIPT = ${JSON.stringify(script)};`,
		"",
	].join("\n");
}

async function main() {
	const next = await renderModule();
	if (check) {
		const current = await readFile(outputPath, "utf8").catch(() => "");
		if (current !== next) {
			console.error(
				`${outputPath} is stale; run \`npm run build:ui\` and commit the result.`,
			);
			process.exit(1);
		}
		console.log("app.generated.ts is current");
		return;
	}
	await writeFile(outputPath, next);
	console.log(`wrote ${outputPath}`);
}

if (
	process.argv[1] &&
	resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	await main();
}
